local Config = require("core.config")
local Rng = require("core.rng")
local Input = require("platform.input")

describe("Config and Rng", function()
  it("merges overrides and rejects unknown or invalid values", function()
    local config = Config.build({ lives = 5 })
    assert.equal(5, config.lives)
    assert.equal(Config.defaults.width, config.width)
    assert.has_error(function()
      Config.build({ speed_of_light = 1 })
    end)
    assert.has_error(function()
      Config.build({ fire_interval = 0 })
    end)
    assert.has_error(function()
      Config.build({ lives = 1.5 })
    end)
  end)

  it("Rng is reproducible and stays in range", function()
    local a, b = Rng.new(99), Rng.new(99)
    for _ = 1, 100 do
      local x = a:range(2, 5)
      assert.equal(x, b:range(2, 5))
      assert.is_true(x >= 2 and x < 5)
      local n = a:int(1, 3)
      b:int(1, 3)
      assert.is_true(n >= 1 and n <= 3)
    end
    assert.has_error(function()
      Rng.new("seed")
    end)
  end)
end)

describe("Input", function()
  it("maps held keys to normalized controls", function()
    local held = { a = true, up = true, space = true }
    local controls = Input.controls(function(key)
      return held[key] == true
    end)
    assert.same({ move_x = -1, move_y = -1, fire = true }, controls)
    local none = Input.controls(function()
      return false
    end)
    assert.same({ move_x = 0, move_y = 0, fire = false }, none)
  end)

  it("parses a seed and --frames, rejecting anything else", function()
    assert.same({ seed = 5 }, Input.parse_args({}, 5))
    assert.same({ seed = 42, frames = 600 }, Input.parse_args({ "42", "--frames", "600" }, 5))
    assert.has_error(function()
      Input.parse_args({ "--frames", "-3" }, 1)
    end)
    assert.has_error(function()
      Input.parse_args({ "--fullscreen" }, 1)
    end)
  end)
end)
